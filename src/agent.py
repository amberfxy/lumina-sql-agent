@dataclass(frozen=True)
class LLMResponse:
    text: str
    prompt_tokens: int = 0
    completion_tokens: int = 0


@dataclass
class DebugAttempt:
    attempt_number: int
    query: str | None
    error: str
    raw_error: str
    category: str = FailureCategory.INTERNAL_ERROR.value
    policy: str = RetryPolicy.TERMINAL.value
    source: str = FailureSource.AGENT.value


@dataclass
class AgentResult:
    success: bool
    backend: DatabaseBackend
    user_query: str
    final_query: str | None
    execution: ExecutionResult | None
    pruned_schema: str
    attempts: list[DebugAttempt] = field(default_factory=list)
    llm_provider: str = ""
    message: str = ""
    cache_hit: bool = False
    llm_calls: int = 0
    duration_ms: float = 0.0
    failure: Failure | None = None
    request_id: str = "-"
    prompt_tokens: int = 0
    completion_tokens: int = 0
    estimated_cost_usd: float = 0.0
    transient_retries: int = 0
    db_executions: int = 0

    def to_dict(self) -> dict[str, Any]:
        return {
            "success": self.success,
            "backend": self.backend.value,
            "user_query": self.user_query,
            "final_query": self.final_query,
            "execution": self.execution.to_dict() if self.execution else None,
            "pruned_schema": self.pruned_schema,
            "attempts": [
                {
                    "attempt_number": attempt.attempt_number,
                    "query": attempt.query,
                    "error": attempt.error,
                    "raw_error": attempt.raw_error,
                    "category": attempt.category,
                    "policy": attempt.policy,
                    "source": attempt.source,
                }
                for attempt in self.attempts
            ],
            "failure": self.failure.to_dict() if self.failure else None,
            "llm_provider": self.llm_provider,
            "message": self.message,
            "cache_hit": self.cache_hit,
            "llm_calls": self.llm_calls,
            "duration_ms": round(self.duration_ms, 2),
            "request_id": self.request_id,
            "usage": {
                "prompt_tokens": self.prompt_tokens,
                "completion_tokens": self.completion_tokens,
                "estimated_cost_usd": round(self.estimated_cost_usd, 6),
            },
            "transient_retries": self.transient_retries,
            "db_executions": self.db_executions,
        }


class LLMClient(Protocol):
    def complete(self, system_prompt: str, user_prompt: str, timeout: float | None = None) -> LLMResponse: ...

    def stream(
        self, system_prompt: str, user_prompt: str, timeout: float | None = None
    ) -> Generator[str, None, LLMResponse]: ...


class OpenAILLMClient:
    def __init__(self, settings: Settings) -> None:
        if not settings.openai_api_key:
            raise ValueError("OPENAI_API_KEY is required when LLM_PROVIDER=openai")
        self.settings = settings
        self.client = OpenAI(
            api_key=settings.openai_api_key.get_secret_value(),
            base_url=settings.openai_base_url,
            timeout=settings.llm_timeout_seconds,
            max_retries=settings.llm_max_retries,
        )

    def _request(self, system_prompt: str, user_prompt: str) -> dict[str, Any]:
        return {
            "model": self.settings.openai_model,
            "temperature": self.settings.llm_temperature,
            "max_tokens": self.settings.llm_max_tokens,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            "extra_headers": {"X-Request-ID": get_request_id()},
        }

    def complete(self, system_prompt: str, user_prompt: str, timeout: float | None = None) -> LLMResponse:
        client = self.client.with_options(timeout=timeout) if timeout else self.client
        response = client.chat.completions.create(**self._request(system_prompt, user_prompt))
        usage = response.usage
        return LLMResponse(
            text=response.choices[0].message.content or "",
            prompt_tokens=usage.prompt_tokens if usage else 0,
            completion_tokens=usage.completion_tokens if usage else 0,
        )

    def stream(
        self, system_prompt: str, user_prompt: str, timeout: float | None = None
    ) -> Generator[str, None, LLMResponse]:
        client = self.client.with_options(timeout=timeout) if timeout else self.client
        stream = client.chat.completions.create(
            **self._request(system_prompt, user_prompt),
            stream=True,
            stream_options={"include_usage": True},
        )
        chunks: list[str] = []
        prompt_tokens = completion_tokens = 0
        for chunk in stream:
            if chunk.usage:
                prompt_tokens, completion_tokens = chunk.usage.prompt_tokens, chunk.usage.completion_tokens
            if not chunk.choices:
                continue
            delta = chunk.choices[0].delta.content
            if delta:
                chunks.append(delta)
                yield delta
        return LLMResponse("".join(chunks), prompt_tokens, completion_tokens)


class AnthropicLLMClient:
    def __init__(self, settings: Settings) -> None:
        if not settings.anthropic_api_key:
            raise ValueError("ANTHROPIC_API_KEY is required when LLM_PROVIDER=anthropic")
        self.settings = settings
        self.client = Anthropic(
            api_key=settings.anthropic_api_key.get_secret_value(),
            timeout=settings.llm_timeout_seconds,
            max_retries=settings.llm_max_retries,
        )

    def _request(self, system_prompt: str, user_prompt: str) -> dict[str, Any]:
        return {
            "model": self.settings.anthropic_model,
            "max_tokens": self.settings.llm_max_tokens,
            "temperature": self.settings.llm_temperature,
            "system": system_prompt,
            "messages": [{"role": "user", "content": user_prompt}],
        }

    def complete(self, system_prompt: str, user_prompt: str, timeout: float | None = None) -> LLMResponse:
        client = self.client.with_options(timeout=timeout) if timeout else self.client
        response = client.messages.create(**self._request(system_prompt, user_prompt))
        text_blocks = [block.text for block in response.content if block.type == "text"]
        return LLMResponse("".join(text_blocks), response.usage.input_tokens, response.usage.output_tokens)

    def stream(
        self, system_prompt: str, user_prompt: str, timeout: float | None = None
    ) -> Generator[str, None, LLMResponse]:
        client = self.client.with_options(timeout=timeout) if timeout else self.client
        chunks: list[str] = []
        with client.messages.stream(**self._request(system_prompt, user_prompt)) as stream:
            for text in stream.text_stream:
                chunks.append(text)
                yield text
            usage = stream.get_final_message().usage
        return LLMResponse("".join(chunks), usage.input_tokens, usage.output_tokens)


def build_llm_client(settings: Settings) -> LLMClient:
    if settings.llm_provider == LLMProvider.ANTHROPIC:
        return AnthropicLLMClient(settings)
    return OpenAILLMClient(settings)


@dataclass
class _RunState:
    started: float
    attempts: list[DebugAttempt] = field(default_factory=list)
    llm_calls: int = 0
    executions: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    transient_retries: int = 0
    pruned_schema: str = ""


class LuminaSQLAgent:
    """Generates queries and executes them under a failure-taxonomy retry policy.

    Only LLM-correctable failures (syntax, unknown table/column, type errors, malformed
    output) go back to the model. Transient database failures are retried as-is without
    the model, and unsafe, permission, timeout, and provider failures end the run.
    `run` and `stream_run` share one event generator so caching, retries, and metrics
    behave identically for synchronous and streaming callers.
    """

    def __init__(
        self,
        settings: Settings | None = None,
        schema_manager: SchemaManager | None = None,
        db_executor: DatabaseExecutor | None = None,
        llm_client: LLMClient | None = None,
        cache: Cache | None = None,
    ) -> None:
        self.settings = settings or get_settings()
        self.cache = cache or NullCache()
        self.db_executor = db_executor or DatabaseExecutor(settings=self.settings)
        self.schema_manager = schema_manager or SchemaManager(
            settings=self.settings, db_executor=self.db_executor, cache=self.cache
        )
        self.llm_client = llm_client or build_llm_client(self.settings)
        self.guard = SQLGuard(schema=self.settings.postgres_schema, denied_columns=self.settings.denied_columns)
        self.max_attempts = self.settings.max_retry_iterations

    def run(
        self,
        user_query: str,
        backend: DatabaseBackend = DatabaseBackend.POSTGRES,
        *,
        allow_mutations: bool = False,
        use_cache: bool = True,
        max_attempts: int | None = None,
    ) -> AgentResult:
        """Execute the full generate -> validate -> execute -> correct loop and return the final result."""
        result: AgentResult | None = None
        for event in self._run_events(
            user_query,
            backend,
            allow_mutations=allow_mutations,
            use_cache=use_cache,
            max_attempts=max_attempts,
            stream_tokens=False,
        ):
            if event["type"] == "result":
                result = event["content"]
        assert result is not None
        return result

    async def arun(
        self,
        user_query: str,
        backend: DatabaseBackend = DatabaseBackend.POSTGRES,
        **kwargs: Any,
    ) -> AgentResult:
        """Run the blocking agent loop in a worker thread so callers can fan out concurrently."""
        return await asyncio.to_thread(self.run, user_query, backend, **kwargs)

    def stream_run(
        self,
        user_query: str,
        backend: DatabaseBackend = DatabaseBackend.POSTGRES,
        *,
        allow_mutations: bool = False,
        use_cache: bool = True,
    ) -> Iterator[dict[str, Any]]:
        """Yield JSON-serializable events for API/UI streaming consumers."""
        for event in self._run_events(
            user_query,
            backend,
            allow_mutations=allow_mutations,
            use_cache=use_cache,
            max_attempts=None,
            stream_tokens=True,
        ):
            if event["type"] == "result":
                yield {"type": "result", "content": event["content"].to_dict()}
            else:
                yield event

    async def astream_run(
        self,
        user_query: str,
        backend: DatabaseBackend = DatabaseBackend.POSTGRES,
        *,
        allow_mutations: bool = False,
        use_cache: bool = True,
    ) -> AsyncIterator[dict[str, Any]]:
        """Async wrapper that advances the blocking generator in a worker thread.

        LLM and database calls are blocking; iterating them directly inside an async
        endpoint would stall the event loop and serialize every concurrent request.
        """
        iterator = self.stream_run(user_query, backend, allow_mutations=allow_mutations, use_cache=use_cache)
        sentinel = object()
        while True:
            event = await asyncio.to_thread(next, iterator, sentinel)
            if event is sentinel:
                return
            yield event

    def _run_events(
        self,
        user_query: str,
        backend: DatabaseBackend,
        *,
        allow_mutations: bool,
        use_cache: bool,
        max_attempts: int | None,
        stream_tokens: bool,
    ) -> Iterator[dict[str, Any]]:
        state = _RunState(started=time.perf_counter())
        max_attempts = max_attempts or self.max_attempts
        deadline = state.started + self.settings.agent_deadline_seconds
        logger.info("Agent run started backend=%s max_attempts=%s", backend.value, max_attempts)

        yield {"type": "status", "message": "Loading schema metadata..."}
        known_tables = self.schema_manager.get_table_names(backend)
        if not known_tables:
            failure = Failure(FailureCategory.SCHEMA_UNAVAILABLE, FailureSource.DATABASE, "Schema catalog is empty.")
            yield self._finish(state, backend, user_query, None, None, failure)
            return
        state.pruned_schema = self.schema_manager.get_pruned_schema(user_query, backend=backend)
        yield {"type": "schema", "content": state.pruned_schema}

        # Mutating runs are never served from or written to the cache.
        cacheable = use_cache and self.cache.enabled and not allow_mutations
        cache_key = self._query_cache_key(user_query, backend, state.pruned_schema) if cacheable else ""
        if cacheable:
            cached_query = self.cache.get(cache_key, kind="query")
            if cached_query:
                yield {"type": "status", "message": "Serving query from cache..."}
                yield {"type": "query", "content": cached_query}
                try:
                    self.guard.validate(cached_query, backend, known_tables=known_tables)
                    execution = self._execute(cached_query, backend, False, state)
                except (QueryRejected, DatabaseExecutionError) as exc:
                    logger.warning("Cached query failed, regenerating: %s", exc)
                    self.cache.delete(cache_key)
                    state.executions = 0
                else:
                    yield self._finish(state, backend, user_query, cached_query, execution, None, cache_hit=True)
                    return

        query_language = self._query_language(backend)
        system_prompt = self._system_prompt(backend)
        prompt = INITIAL_SQL_PROMPT.format(
            query_language=query_language,
            pruned_schema=state.pruned_schema,
            user_query=_neutralize_tags(user_query),
        )
        phase = "generate"
        current_query: str | None = None

        for attempt_number in range(1, max_attempts + 1):
            if time.perf_counter() > deadline:
                failure = Failure(FailureCategory.TIMEOUT, FailureSource.AGENT, "Agent deadline exceeded.")
                yield self._finish(state, backend, user_query, current_query, None, failure)
                return

            yield {"type": "status", "message": f"Generating query (attempt {attempt_number}/{max_attempts})..."}
            try:
                response = yield from self._call_llm(system_prompt, prompt, phase, stream_tokens, state, deadline)
            except Exception as exc:  # noqa: BLE001 - provider SDK errors are classified, not propagated
                logger.warning("LLM call failed: %s: %s", exc.__class__.__name__, exc)
                failure = Failure(classify_llm_error(exc), FailureSource.LLM, f"{exc.__class__.__name__}: {exc}"[:500])
                yield self._finish(state, backend, user_query, current_query, None, failure)
                return

            current_query, refusal = self._parse_response(response.text)
            if refusal is not None:
                failure = Failure(FailureCategory.UNANSWERABLE, FailureSource.LLM, refusal or "Model declined.")
                yield self._finish(state, backend, user_query, None, None, failure)
                return
            yield {"type": "query", "content": current_query}

            try:
                if not current_query:
                    raise QueryRejected(FailureCategory.MALFORMED_OUTPUT, "The response did not contain a query.")
                self.guard.validate(current_query, backend, known_tables=known_tables, allow_mutations=allow_mutations)
                yield {"type": "status", "message": f"Executing query (attempt {attempt_number}/{max_attempts})..."}
                execution = self._execute(current_query, backend, allow_mutations, state)
            except QueryRejected as exc:
                failure = Failure(exc.category, FailureSource.VALIDATOR, exc.reason)
            except DatabaseExecutionError as exc:
                failure = Failure(exc.category, FailureSource.DATABASE, exc.raw_error)
            else:
                if cacheable:
                    self.cache.set(cache_key, current_query, ttl_seconds=self.settings.query_cache_ttl_seconds)
                yield self._finish(state, backend, user_query, current_query, execution, None)
                return

            state.attempts.append(
                DebugAttempt(
                    attempt_number=attempt_number,
                    query=current_query,
                    error=failure.message[:500],
                    raw_error=failure.message,
                    category=failure.category.value,
                    policy=failure.policy.value,
                    source=failure.source.value,
                )
            )
            AGENT_ATTEMPT_FAILURES.labels(
                backend=backend.value, category=failure.category.value, policy=failure.policy.value
            ).inc()
            logger.warning(
                "Attempt %s failed category=%s policy=%s error=%s",
                attempt_number,
                failure.category.value,
                failure.policy.value,
                failure.message[:300],
            )
            yield {"type": "error", "content": {"attempt": attempt_number, "query": current_query, **failure.to_dict()}}

            if failure.policy != RetryPolicy.LLM_CORRECTABLE or attempt_number >= max_attempts:
                yield self._finish(state, backend, user_query, current_query, None, failure)
                return

            prompt = DEBUG_SQL_PROMPT.format(
                query_language=query_language,
                pruned_schema=state.pruned_schema,
                user_query=_neutralize_tags(user_query),
                failed_query=current_query or "(none)",
                category=failure.category.value,
                error_log=_neutralize_tags(failure.message[:1500]),
                attempt_number=attempt_number + 1,
                max_attempts=max_attempts,
            )
            phase = "debug"

    def _execute(
        self, query: str, backend: DatabaseBackend, allow_mutations: bool, state: _RunState
    ) -> ExecutionResult:
        """Execute with bounded same-query retries for transient failures."""
        retries = self.settings.db_transient_retries
        for retry in range(retries + 1):
            state.executions += 1
            try:
                return self.db_executor.execute(query, backend=backend, allow_mutations=allow_mutations)
            except DatabaseExecutionError as exc:
                if policy_for(exc.category, FailureSource.DATABASE) != RetryPolicy.TRANSIENT or retry == retries:
                    raise
                state.transient_retries += 1
                TRANSIENT_RETRIES.labels(backend=backend.value, category=exc.category.value).inc()
                delay = self.settings.db_retry_backoff_seconds * (2**retry)
                logger.warning("Transient %s, retrying same query in %.2fs", exc.category.value, delay)
                time.sleep(delay)
        raise AssertionError("unreachable")

    def _finish(
        self,
        state: _RunState,
        backend: DatabaseBackend,
        user_query: str,
        final_query: str | None,
        execution: ExecutionResult | None,
        failure: Failure | None,
        *,
        cache_hit: bool = False,
    ) -> dict[str, Any]:
        duration = time.perf_counter() - state.started
        had_correctable = any(attempt.policy == RetryPolicy.LLM_CORRECTABLE.value for attempt in state.attempts)
        if failure is None:
            outcome = "cache_hit" if cache_hit else ("self_corrected" if state.attempts else "success")
            message = "Query executed successfully" + (" (cached)." if cache_hit else ".")
        else:
            outcome = (
                "rejected"
                if failure.category in (FailureCategory.UNSAFE_QUERY, FailureCategory.UNANSWERABLE)
                else "failed"
            )
            message = f"{failure.category.value}: {failure.message}"
            AGENT_RUN_FAILURES.labels(backend=backend.value, category=failure.category.value).inc()
            if failure.category in (FailureCategory.UNSAFE_QUERY, FailureCategory.PERMISSION_ERROR):
                UNSAFE_REJECTIONS.labels(backend=backend.value, layer=failure.source.value).inc()
        if had_correctable:
            SELF_CORRECTION.labels(
                backend=backend.value, result="recovered" if failure is None else "not_recovered"
            ).inc()
        AGENT_RUNS.labels(backend=backend.value, outcome=outcome).inc()
        AGENT_LATENCY.labels(backend=backend.value).observe(duration)
        if state.executions:
            AGENT_ATTEMPTS.labels(backend=backend.value).observe(state.executions)
        logger.info(
            "Agent run finished outcome=%s llm_calls=%s tokens=%s/%s duration_ms=%.1f",
            outcome,
            state.llm_calls,
            state.prompt_tokens,
            state.completion_tokens,
            duration * 1000,
        )
        return {
            "type": "result",
            "content": AgentResult(
                success=failure is None,
                backend=backend,
                user_query=user_query,
                final_query=final_query,
                execution=execution,
                pruned_schema=state.pruned_schema,
                attempts=state.attempts,
                llm_provider=self.settings.llm_provider.value,
                message=message,
                cache_hit=cache_hit,
                llm_calls=state.llm_calls,
                duration_ms=duration * 1000,
                failure=failure,
                request_id=get_request_id(),
                prompt_tokens=state.prompt_tokens,
                completion_tokens=state.completion_tokens,
                estimated_cost_usd=self._estimate_cost(state.prompt_tokens, state.completion_tokens),
                transient_retries=state.transient_retries,
                db_executions=state.executions,
            ),
        }

    def _call_llm(
        self,
        system_prompt: str,
        user_prompt: str,
        phase: str,
        stream_tokens: bool,
        state: _RunState,
        deadline: float,
    ) -> Generator[dict[str, Any], None, LLMResponse]:
        """Call the LLM, optionally yielding token events; returns the full response with usage."""
        provider = self.settings.llm_provider.value
        model = self.settings.active_llm_model
        started = time.perf_counter()
        # The SDK retries timeouts internally, so split the remaining run budget across its
        # attempts; otherwise one call can outlive the agent deadline by several multiples.
        per_try = (deadline - started) / (self.settings.llm_max_retries + 1)
        timeout = max(1.0, min(self.settings.llm_timeout_seconds, per_try))
        status = "ok"
        state.llm_calls += 1
        try:
            if not stream_tokens:
                response = self.llm_client.complete(system_prompt, user_prompt, timeout=timeout)
            else:
                chunks: list[str] = []
                stream = self.llm_client.stream(system_prompt, user_prompt, timeout=timeout)
                while True:
                    try:
                        chunk = next(stream)
                    except StopIteration as stop:
                        response = stop.value or LLMResponse("".join(chunks))
                        break
                    chunks.append(chunk)
                    yield {"type": "llm_token", "content": chunk}
        except Exception:
            status = "error"
            raise
        finally:
            elapsed = time.perf_counter() - started
            LLM_CALLS.labels(provider=provider, phase=phase, status=status).inc()
            LLM_LATENCY.labels(provider=provider, phase=phase).observe(elapsed)

        state.prompt_tokens += response.prompt_tokens
        state.completion_tokens += response.completion_tokens
        LLM_TOKENS.labels(provider=provider, model=model, kind="prompt").inc(response.prompt_tokens)
        LLM_TOKENS.labels(provider=provider, model=model, kind="completion").inc(response.completion_tokens)
        LLM_COST.labels(provider=provider, model=model).inc(
            self._estimate_cost(response.prompt_tokens, response.completion_tokens)
        )
        logger.info(
            "LLM call phase=%s latency_ms=%.1f tokens=%s/%s",
            phase,
            elapsed * 1000,
            response.prompt_tokens,
            response.completion_tokens,
        )
        return response

    def _estimate_cost(self, prompt_tokens: int, completion_tokens: int) -> float:
        return (
            prompt_tokens * self.settings.llm_input_cost_per_1m_tokens
            + completion_tokens * self.settings.llm_output_cost_per_1m_tokens
        ) / 1_000_000

    def _query_cache_key(self, user_query: str, backend: DatabaseBackend, pruned_schema: str) -> str:
        # Keyed on the pruned schema and prompt version so schema or prompt changes invalidate stale queries.
        normalized_question = _WHITESPACE_PATTERN.sub(" ", user_query.strip().lower())
        digest = hashlib.sha256(
            "\x1f".join(
                [
                    PROMPT_VERSION,
                    backend.value,
                    self.settings.llm_provider.value,
                    self.settings.active_llm_model,
                    normalized_question,
                    pruned_schema,
                ]
            ).encode()
        ).hexdigest()
        return f"query:{digest}"

    @staticmethod
    def _query_language(backend: DatabaseBackend) -> str:
        return "PartiQL" if backend == DatabaseBackend.DYNAMODB else "SQL"

    @staticmethod
    def _system_prompt(backend: DatabaseBackend) -> str:
        if backend == DatabaseBackend.DYNAMODB:
            return "You generate safe, read-only AWS DynamoDB PartiQL. Never invent tables or attributes."
        return "You generate safe, read-only PostgreSQL SQL. Never invent tables or columns."

    @classmethod
    def _parse_response(cls, llm_response: str) -> tuple[str, str | None]:
        """Return (query, refusal_reason). A refusal is only honored when no query was produced."""
        query = cls._extract_query(llm_response)
        if not query:
            refusal = _REFUSAL_PATTERN.search(llm_response)
            if refusal:
                return "", refusal.group(1).strip()
        return query, None

    @staticmethod
    def _extract_query(llm_response: str) -> str:
        match = _CODE_FENCE_PATTERN.search(llm_response)
        if match:
            return match.group(1).strip()

        stripped = llm_response.strip()
        if stripped.startswith("{"):
            try:
                payload = json.loads(stripped)
                statement = payload.get("statement") or payload.get("Statement")
                if statement:
                    return str(statement).strip()
            except (json.JSONDecodeError, AttributeError):
                pass
        # Unfenced output is accepted only if it looks like a query; prose is malformed output.
        return stripped if _BARE_QUERY_PATTERN.match(stripped) else ""


def _neutralize_tags(text: str) -> str:
    """Stop untrusted text from closing the prompt's data delimiters."""
    return text.replace("</", "<\\/")
